        if re.search(r"\b(устал|задолбал|болею|тяжел(ый|о)|грустн|надоел|проблем|завал|вымотал)\b", cleaned):
            return "CARING_SUPPORT"

        # 4. Pushy, Arrogant, or Rude -> Confident Sarcasm & Boundary
        if re.search(r"\b(быстро|скинь номер|поехали ко мне|че молчишь|ты обязана|покажи сиськи)\b", cleaned):
            return "CONFIDENT_BOUNDARY"

        # 5. Short and dry (1-2 words without smiles/emojis)
        words = cleaned.split()
        if len(words) <= 2 and not any(c in cleaned for c in [")", "(", "!", "?", "🔥", "😊", "😂", "хах"]):
            return "SHORT_DRY"

